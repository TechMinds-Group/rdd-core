-- Schema legado extraído do Oracle do sistema desktop (amostra)
CREATE TABLE SDA_BLOQUEIO (
  NRO_INT_BLOQUEIO NUMBER(10) NOT NULL,
  NRO_INT_PRODUTOR NUMBER(10) NOT NULL,
  TXT_MOTIVO VARCHAR2(400),
  DTH_INICIO DATE DEFAULT SYSDATE NOT NULL,
  DTH_FIM DATE,
  FLG_SITUACAO CHAR(1) DEFAULT 'A' NOT NULL,
  CTR_DTH_INC DATE DEFAULT SYSDATE NOT NULL,
  CTR_USU_INC NUMBER(8) NOT NULL,
  CONSTRAINT PK_SDA_BLOQUEIO PRIMARY KEY (NRO_INT_BLOQUEIO),
  CONSTRAINT CK_FLG_SIT CHECK (FLG_SITUACAO IN ('A','E'))
);
CREATE INDEX IDX_BLOQ_PRODUTOR ON SDA_BLOQUEIO (NRO_INT_PRODUTOR);

CREATE SEQUENCE SEQ_SDA_BLOQUEIO START WITH 1 INCREMENT BY 1;
